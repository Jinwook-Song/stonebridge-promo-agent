// Copies the sample posts and quotes made in the public demo into demo/samples.ts, so every
// daily reset brings them back. Run after making the samples in the demo itself:
//   npx tsx scripts/demo-snapshot.ts
// Reads the demo D1 only (CLOUDFLARE_ENV=demo). Their photos must stay in the demo R2 bucket.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";

const TABLES = ["posts", "photos", "drafts", "quotes", "quote_versions"] as const;

function rows(table: string): Record<string, unknown>[] {
  const out = execFileSync(
    "npx",
    ["wrangler", "d1", "execute", "promo-demo", "--remote", "--json", "--command", `SELECT * FROM ${table} ORDER BY id`],
    { env: { ...process.env, CLOUDFLARE_ENV: "demo" }, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  );
  const parsed = JSON.parse(out) as { results: Record<string, unknown>[] }[];
  return parsed[0].results;
}

const samples: Record<string, Record<string, unknown>[]> = {};
for (const table of TABLES) {
  const list = rows(table);
  // A sample must look finished: no run in flight, no Kakao claim.
  samples[table] = list.map((r) =>
    table === "posts" ? { ...r, status: r.status === "generating" ? "ready" : r.status, draft_notified_at: null } : r,
  );
}

const file = path.join(import.meta.dirname, "..", "demo", "samples.ts");
writeFileSync(
  file,
  `import type { DemoSeed } from "../app/demo/seed-sql";

// Generated by scripts/demo-snapshot.ts from the demo D1: the sample posts and quotes made in the
// demo itself. Do not edit by hand; make them again in the demo and re-run the script.
export const SAMPLES: DemoSeed = ${JSON.stringify(samples, null, 2)};
`,
);
console.log(`wrote ${file}: ${TABLES.map((t) => `${t} ${samples[t].length}`).join(", ")}`);
