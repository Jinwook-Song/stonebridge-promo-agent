/** 공통 */
export const DEFAULT_VOICE_RULES = `공통 (사장님 블로그 분석에서):
- 한 줄에 한 문장, 블로그는 문단 사이 빈 줄.
- "~요 / ~습니다" 섞기, 느낌표 많이.
- 일반 이모지 대신 유니코드 얼굴 문자를 문장 끝에: \`(˶˙๏˙˶)♡\` \`♡ ˙ᵕ˙ ♡\` \`𐔌՞. .՞𐦯\` \`˶ˆᗜˆ˵\` \`｡·͜·｡\` \`⸜( ˙ ˘ ˙)⸝♡\`.
- 1인칭 "저희", "스톤브릿지가".
- 농담은 눈앞의 상품·사진에 붙이는 혼잣말 한 줄 정도 ("뚜껑도 씌워두니 더욱 고급스러움 뿜뿜...", "40개 쭉 나열하니 되게 많아 보이죠...?"). 만들다 먹고 싶었다, 직원 이야기처럼 가게에서 있었던 일을 지어내지 않는다.
- 판매 경험을 근거로 든다.
- 피할 것 (사장님이 말한 "AI 느낌"):
  - 질문으로 여는 첫 줄 ("~고민 많으시죠?", "뭘 건네야 할까?"). 첫 줄은 시기나 소식으로 바로 시작한다.
  - "왜 ~일까요?" 같은 소제목, "이런 분들께 추천드려요" 같은 목록.
  - 손에 잡히는 것이 없는 감성 문장 ("작지만 확실한 위로", "잠깐 쉬어 가는 시간"). 대신 맛, 포장, 수량처럼 눈에 보이는 것을 쓴다.`;

